@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CategoriesScreen(onNavigateBack: () -> Unit) {
    var showIncome by remember { mutableStateOf(true) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Categorías") },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Volver")
                    }
                },
            )
        },
        floatingActionButton = {
            FloatingActionButton(onClick = { /* TODO: add category dialog */ }) {
                Icon(Icons.Default.Add, contentDescription = "Nueva categoría")
            }
        },
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .padding(16.dp),
        ) {
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                FilterChip(
                    selected = showIncome,
                    onClick = { showIncome = true },
                    label = { Text("Ingresos") },
                )
                FilterChip(
                    selected = !showIncome,
                    onClick = { showIncome = false },
                    label = { Text("Egresos") },
                )
            }
            Spacer(modifier = Modifier.height(16.dp))

            // TODO: replace with LazyColumn of categories
            Column(
                modifier = Modifier.fillMaxSize(),
                horizontalAlignment = Alignment.CenterHorizontally,
                verticalArrangement = Arrangement.Center,
            ) {
                Text(
                    text = "No hay categorías personalizadas",
                    style = MaterialTheme.typography.bodyLarge,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
    }
}
